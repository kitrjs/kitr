// Usage: node scripts/api-docs.mjs [--check]
// Writes packages/<name>/docs/api.md from each package's built type definitions (run `pnpm build`
// first): every export of every entry point, with its signature and its doc comment. Packages
// with a hand-written api.md (no GENERATED marker) are left alone. --check fails when a
// generated page is out of date.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import ts from 'typescript'

const MARKER = '<!-- GENERATED by scripts/api-docs.mjs from the type definitions. Do not edit. -->'
const check = process.argv.includes('--check')
const stale = []

const pkgs = readdirSync('packages')
  .map((dir) => ({ dir, file: join('packages', dir, 'package.json') }))
  .filter(({ file }) => existsSync(file))
  .map(({ dir, file }) => ({ dir, pkg: JSON.parse(readFileSync(file, 'utf8')) }))
  .filter(({ pkg }) => pkg.kitr)

const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed })
/** Keeps member doc comments, for interfaces and object types. */
const commented = ts.createPrinter({ removeComments: false, newLine: ts.NewLineKind.LineFeed })

/** Entry points with their public import path: `.` → kitr/storage, `./react` → kitr/storage/react. */
function entries(dir, pkg) {
  const out = []
  for (const [key, value] of Object.entries(pkg.exports ?? {})) {
    // The setup module and command modules face the CLI, not the app; they have no kitr/* entry.
    if (key === './kitr' || key === './commands') continue
    const types = typeof value === 'string' ? value : value.types
    if (!types?.endsWith('.d.ts')) continue
    const file = join('packages', dir, types)
    if (!existsSync(file)) continue
    out.push({ path: `kitr/${pkg.kitr.name}${key === '.' ? '' : key.slice(1)}`, file })
  }
  return out
}

const kindOrder = (decl) => {
  if (ts.isFunctionDeclaration(decl)) return 0
  if (ts.isClassDeclaration(decl)) return 1
  if (ts.isVariableDeclaration(decl)) return 2
  if (ts.isInterfaceDeclaration(decl)) return 3
  if (ts.isTypeAliasDeclaration(decl)) return 4
  return 5
}

/** Declaration text without comments or `declare`/`export` noise, renamed to the export name. */
function signature(decl, name, sf) {
  let node = decl
  if (ts.isVariableDeclaration(decl)) node = decl.parent.parent
  const keep =
    ts.isInterfaceDeclaration(decl) ||
    ts.isTypeAliasDeclaration(decl) ||
    ts.isClassDeclaration(decl)
  let text = (keep ? commented : printer).printNode(ts.EmitHint.Unspecified, node, sf)
  // The declaration's own doc comment is shown under the code block instead.
  text = text.replace(/^\s*\/\*\*[\s\S]*?\*\/\s*/, '')
  text = text.replace(/^(export\s+)?(declare\s+)?(default\s+)?/gm, '')
  const original = decl.name && ts.isIdentifier(decl.name) ? decl.name.text : undefined
  if (original && original !== name) text = text.replace(new RegExp(`\\b${original}\\b`), name)
  return text.replace(/ {4}/g, '  ').trim()
}

function docOf(symbol, checker) {
  const text = ts.displayPartsToString(symbol.getDocumentationComment(checker)).trim()
  const tags = symbol
    .getJsDocTags(checker)
    .filter((t) => t.name === 'example' || t.name === 'deprecated')
    .map((t) => {
      const body = ts.displayPartsToString(t.text ?? []).trim()
      if (t.name === 'deprecated') return `**Deprecated.** ${body}`
      return body.includes('\n') || body.startsWith('```') ? body : `\`${body}\``
    })
  return [text, ...tags].filter(Boolean).join('\n\n')
}

/** Doc comments use indented code samples (`*   const x = ...`); turn them into fenced blocks. */
function fenceIndented(text) {
  const lines = text.split('\n')
  const out = []
  let block = []
  const flush = () => {
    if (!block.length) return
    while (block.length && !block.at(-1).trim()) block.pop()
    const indent = Math.min(...block.filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length))
    out.push('```ts', ...block.map((l) => l.slice(indent)), '```')
    block = []
  }
  for (const line of lines) {
    if (/^ {2,}\S/.test(line) || (block.length && !line.trim())) block.push(line)
    else {
      flush()
      out.push(line)
    }
  }
  flush()
  return out.join('\n').replace(/\n{3,}/g, '\n\n')
}

function render({ dir, pkg }) {
  const list = entries(dir, pkg)
  if (!list.length) return null
  const program = ts.createProgram(
    list.map((e) => e.file),
    {
      allowJs: false,
      skipLibCheck: true,
      jsx: ts.JsxEmit.ReactJSX,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022,
    },
  )
  const checker = program.getTypeChecker()
  const sections = []
  for (const entry of list) {
    const sf = program.getSourceFile(entry.file)
    const moduleSymbol = sf && checker.getSymbolAtLocation(sf)
    if (!moduleSymbol) continue
    const upstream = new Set()
    const items = []
    for (const exp of checker.getExportsOfModule(moduleSymbol)) {
      if (exp.name === 'default') continue
      const symbol = exp.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exp) : exp
      const decls = symbol.declarations ?? []
      if (!decls.length) continue
      const file = decls[0].getSourceFile().fileName
      const rel = relative(process.cwd(), file)
      if (rel.includes(`node_modules${sep}`)) {
        const m = rel.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/g)
        const name = m?.at(-1)?.replace('node_modules/', '')
        // Our own packages, re-exported: treat as part of this API. Upstream: just name it.
        if (name && !name.startsWith('@kitr/')) {
          upstream.add(name.replace(/^@types\//, ''))
          continue
        }
      }
      const usable = decls.filter(
        (d) =>
          ts.isFunctionDeclaration(d) ||
          ts.isClassDeclaration(d) ||
          ts.isVariableDeclaration(d) ||
          ts.isInterfaceDeclaration(d) ||
          ts.isTypeAliasDeclaration(d) ||
          ts.isEnumDeclaration(d),
      )
      if (!usable.length) continue
      const sigs = [...new Set(usable.map((d) => signature(d, exp.name, d.getSourceFile())))]
      items.push({ name: exp.name, order: kindOrder(usable[0]), sigs, doc: docOf(symbol, checker) })
    }
    items.sort((a, b) => a.order - b.order || a.name.localeCompare(b.name))
    if (!items.length && !upstream.size) continue
    const lines = [`## ${entry.path}`, '']
    if (upstream.size)
      lines.push(
        `Re-exports ${[...upstream]
          .sort()
          .map((u) => `\`${u}\``)
          .join(', ')} unchanged, plus the following.`,
        '',
      )
    for (const item of items) {
      lines.push(`### ${item.name}`, '', '```ts', item.sigs.join('\n\n'), '```', '')
      if (item.doc) lines.push(fenceIndented(item.doc), '')
    }
    sections.push(lines.join('\n'))
  }
  if (!sections.length) return null
  const mainPath = `kitr/${pkg.kitr.name}`
  return `---
title: API
description: Every export of ${mainPath}, with its signature.
order: 2
---

# API

Every export of ${list.map((e) => `\`${e.path}\``).join(', ')}, read from the published type definitions. The [guide](/packages/${pkg.kitr.name}) shows them in use.

${sections.join('\n')}
${MARKER}
`.replace(/\n{3,}/g, '\n\n')
}

for (const p of pkgs) {
  const docsDir = join('packages', p.dir, p.pkg.kitr.docs ?? 'docs')
  const target = join(docsDir, 'api.md')
  if (existsSync(target) && !readFileSync(target, 'utf8').includes(MARKER)) continue
  const md = render(p)
  if (!md) continue
  if (check) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== md) stale.push(target)
  } else writeFileSync(target, md)
}

if (check && stale.length) {
  console.error(`Out of date, run \`pnpm docs:api\`:\n  ${stale.join('\n  ')}`)
  process.exit(1)
}
if (!check) console.log('API pages written')
