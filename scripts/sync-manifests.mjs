// Usage: node scripts/sync-manifests.mjs [--check]
// Reads the `kitr` block from every packages/*/package.json and writes
// packages/cli/src/manifests.gen.ts. With --check, fails if that file is stale.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const out = 'packages/cli/src/manifests.gen.ts'
// Kits (`kitr new --kit server`) and packages (`kitr add server`) are separate namespaces, so a
// kit may carry the name of the package it is built around.
const manifests = {}
const kits = {}
for (const dir of readdirSync('packages').sort()) {
  const file = join('packages', dir, 'package.json')
  if (!existsSync(file)) continue
  const pkg = JSON.parse(readFileSync(file, 'utf8'))
  if (!pkg.kitr) continue
  const into = pkg.kitr.kind === 'kit' ? kits : manifests
  if (into[pkg.kitr.name]) {
    console.error(
      `${pkg.name} and ${into[pkg.kitr.name].package} both declare the name "${pkg.kitr.name}"`,
    )
    process.exit(1)
  }
  // `"private": true` keeps a package off npm; the CLI and kitr.dev treat it as a preview.
  into[pkg.kitr.name] = {
    package: pkg.name,
    ...pkg.kitr,
    ...(pkg.private ? { preview: true } : {}),
  }
}
const body = `// Generated by scripts/sync-manifests.mjs from each package's "kitr" block. Do not edit.
import type { KitrManifest } from './manifest'

/** Packages and platforms, by short name. */
export const manifests: Record<string, KitrManifest & { package: string }> = ${JSON.stringify(manifests, null, 2)}

/** Kits (\`kitr new --kit <name>\`), by short name. */
export const kitManifests: Record<string, KitrManifest & { package: string }> = ${JSON.stringify(kits, null, 2)}
`
if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : ''
  if (current !== body) {
    console.error(`${out} is out of date. Run: pnpm manifests`)
    process.exit(1)
  }
  console.log(
    `${Object.keys(manifests).length} manifests and ${Object.keys(kits).length} kits in sync`,
  )
} else {
  writeFileSync(out, body)
  console.log(
    `Wrote ${Object.keys(manifests).length} manifests and ${Object.keys(kits).length} kits to ${out}`,
  )
}
