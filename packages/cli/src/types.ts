import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import {
  type GenerateContext,
  type GeneratedFile,
  globToRegExp,
  pickTypesGenerator,
  type TypesGenerator,
} from '@kitr/core'
import { log, type ProjectContext, type RcInfo } from './context'
import { manifests } from './manifests.gen'
import { type LoadedPackage, loadPackage } from './packages'
import { literal } from './platforms'

/**
 * `kitr types`: run every type generator the project's packages declare and write their files
 * under `.kitr/`. A generator is a package's `./types` export (declared as `types` in its `kitr`
 * manifest block) made with `defineTypes()` from `@kitr/core`; the `platforms` generator is built
 * into the CLI because every project has platforms. The runner writes only files whose content
 * changed, so editors and the Vite dev server see no spurious updates, and `--check` reports
 * stale files instead of writing them.
 */

/** Where generated files live, relative to the project root. */
export const GENERATED_DIR = '.kitr'

export interface TypesRunResult {
  /** Files written, relative to the root. */
  written: string[]
  /** Files already up to date. */
  unchanged: string[]
  /** With `check`: files whose content differs from what the generators produce. */
  stale: string[]
  /** The generators that ran, by name. */
  generators: string[]
}

export interface TypesRunOptions {
  /** Report stale files instead of writing. */
  check?: boolean
  /** Run only these generators (by name). */
  only?: string[]
  /** Print a line per file written. Default: true. */
  quiet?: boolean
}

/** The built-in generator: `.kitr/platforms.d.ts` from the `platforms` block of kitrrc.ts. */
// kitr-allow-module-state: constant generator definition, never mutated
export const platformsGenerator: TypesGenerator = {
  name: 'platforms',
  watch: ['kitrrc.ts', 'kitrrc.mts', 'kitrrc.js', 'kitrrc.mjs'],
  generate: (ctx) => [{ file: 'platforms.d.ts', content: renderPlatforms(ctx.rc.platforms) }],
}

export function renderPlatforms(platforms: RcInfo['platforms']): string {
  const names = Object.keys(platforms).sort()
  const lines = names.map((name) => {
    const p = platforms[name]!
    const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name)
    return `    ${key}: { type: '${p.factory}'; options: ${literal(p.options ?? {})} }`
  })
  const union = (values: string[]) =>
    [...new Set(values)]
      .sort()
      .map((v) => `'${v}'`)
      .join(' | ')
  // `kitr dev <name>` defines import.meta.env.KITR_PLATFORM; typing it as the union of names lets
  // `if (import.meta.env.KITR_PLATFORM === 'phone')` be checked by the compiler and dropped by the bundler.
  const env = names.length
    ? `
declare global {
  interface ImportMetaEnv {
    /** The platform from kitrrc.ts this bundle was built for (\`kitr dev <name>\`). */
    readonly KITR_PLATFORM: ${union(names)}
    /** The type of that platform (\`web\`, \`mobile\`...). */
    readonly KITR_PLATFORM_TYPE: ${union(names.map((n) => platforms[n]!.factory))}
  }
}
`
    : ''
  return `// Generated by \`kitr types\` from kitrrc.ts. Do not edit.
declare module '@kitr/core' {
  interface KitrPlatforms {
${lines.join('\n')}
  }
}
${env}export {}
`
}

/**
 * The generators for a project: the built-in `platforms` and one per package. A package on the
 * package contract declares it as `types: () => import('./types')` in its setup module; one
 * without a setup module still works through `kitr.types` in its manifest.
 */
export async function loadGenerators(ctx: ProjectContext): Promise<TypesGenerator[]> {
  const rc = ctx.readRc()
  const out: TypesGenerator[] = [platformsGenerator]
  const deps: Record<string, string> = { ...ctx.pkg.dependencies, ...ctx.pkg.devDependencies }
  const candidates = new Set<string>([...rc.packages, ...Object.keys(deps)])
  for (const name of candidates) {
    if (!name.startsWith('@kitr/') && !typesExportOf(ctx, name)) continue
    let loaded: LoadedPackage | undefined
    try {
      loaded = await loadPackage(ctx, name)
    } catch {
      loaded = undefined
    }
    let mod: unknown
    let specifier: string
    if (loaded?.definition.types) {
      specifier = `${name}/kitr (types)`
      mod = await loaded.definition.types()
    } else {
      const subpath = typesExportOf(ctx, name)
      if (!subpath) continue
      specifier = `${name}/${subpath.replace(/^\.\//, '')}`
      mod = await importFromProject(ctx, specifier)
    }
    const generator = pickTypesGenerator(mod)
    if (!generator)
      throw new Error(
        `${specifier} does not export a generator: use \`export default defineTypes({ ... })\` from @kitr/core`,
      )
    out.push(generator)
  }
  return out
}

/** The `kitr.types` subpath of an installed package, read from its package.json, or the manifest the CLI ships. */
function typesExportOf(ctx: ProjectContext, name: string): string | undefined {
  const file = ctx.path('node_modules', name, 'package.json')
  if (existsSync(file)) {
    try {
      const pkg = JSON.parse(readFileSync(file, 'utf8'))
      return typeof pkg.kitr?.types === 'string' ? pkg.kitr.types : undefined
    } catch {}
  }
  const known = Object.values(manifests).find((m) => m.package === name)
  return known?.types
}

/** Import from the project's own node_modules, with the CLI's resolution as the fallback. */
async function importFromProject(ctx: ProjectContext, specifier: string): Promise<unknown> {
  const { createJiti } = await import('jiti')
  const jiti = createJiti(ctx.path('package.json'), { interopDefault: true })
  try {
    return await jiti.import(specifier)
  } catch (error) {
    try {
      return await import(specifier)
    } catch {
      throw error
    }
  }
}

/** The watch globs of every generator, relative to the project root. */
export function watchGlobsOf(generators: TypesGenerator[], rc: RcInfo): string[] {
  const out = new Set<string>()
  for (const g of generators) {
    const globs = typeof g.watch === 'function' ? g.watch(rc) : (g.watch ?? [])
    for (const glob of globs) out.add(glob)
  }
  return [...out]
}

/** The generators whose watch globs match a changed file (relative to the root). */
export function generatorsFor(generators: TypesGenerator[], rc: RcInfo, file: string) {
  return generators.filter((g) => {
    const globs = typeof g.watch === 'function' ? g.watch(rc) : (g.watch ?? [])
    return globs.some((glob) => globToRegExp(glob).test(file))
  })
}

export function createGenerateContext(ctx: ProjectContext): GenerateContext {
  const rc = ctx.readRc()
  return {
    root: ctx.root,
    rc,
    glob: (dir, pattern) => {
      const base = ctx.path(dir)
      if (!existsSync(base) || !statSync(base).isDirectory()) return []
      const re = globToRegExp(pattern)
      const out: string[] = []
      for (const file of walk(base)) {
        const insideDir = relative(base, file).split('\\').join('/')
        if (re.test(insideDir)) out.push(relative(ctx.root, file).split('\\').join('/'))
      }
      return out.sort()
    },
    exists: (path) => existsSync(ctx.path(path)),
    read: (path) => readFileSync(ctx.path(path), 'utf8'),
    importPath: (file) => {
      const rel = relative(ctx.path(GENERATED_DIR), ctx.path(file))
        .split('\\')
        .join('/')
        .replace(/\.(ts|tsx|js|jsx|mts|mjs)$/, '')
      return rel.startsWith('.') ? rel : `./${rel}`
    },
  }
}

function* walk(dir: string): Generator<string> {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (entry === 'node_modules' || entry.startsWith('.')) continue
    if (statSync(full).isDirectory()) yield* walk(full)
    else yield full
  }
}

/** Run the generators (all, or `only` some) and write what changed under `.kitr/`. */
export async function runTypes(
  ctx: ProjectContext,
  options: TypesRunOptions = {},
  generators?: TypesGenerator[],
): Promise<TypesRunResult> {
  const all = generators ?? (await loadGenerators(ctx))
  const selected = options.only ? all.filter((g) => options.only!.includes(g.name)) : all
  const generateCtx = createGenerateContext(ctx)
  const result: TypesRunResult = { written: [], unchanged: [], stale: [], generators: [] }
  for (const generator of selected) {
    let files: GeneratedFile[]
    try {
      files = await generator.generate(generateCtx)
    } catch (error) {
      throw new Error(
        `kitr types: the ${generator.name} generator failed: ${(error as Error).message}`,
        {
          cause: error,
        },
      )
    }
    result.generators.push(generator.name)
    for (const { file, content } of files) {
      const rel = `${GENERATED_DIR}/${file}`
      const full = ctx.path(rel)
      const current = existsSync(full) ? readFileSync(full, 'utf8') : undefined
      if (current === content) {
        result.unchanged.push(rel)
        continue
      }
      if (options.check) {
        result.stale.push(rel)
        continue
      }
      mkdirSync(dirname(full), { recursive: true })
      writeFileSync(full, content)
      result.written.push(rel)
      if (!options.quiet) log.step(`write ${rel}`)
    }
  }
  return result
}

/** Run the generators after `kitr new` / `kitr add`, warning instead of failing when one cannot load yet. */
export async function generateTypesQuietly(ctx: ProjectContext) {
  try {
    const result = await runTypes(ctx, { quiet: true })
    if (result.written.length)
      log.step(
        `kitr types: ${result.written.length} file(s) written (${result.generators.join(', ')})`,
      )
  } catch (error) {
    log.warn(`kitr types: ${(error as Error).message}`)
  }
}
