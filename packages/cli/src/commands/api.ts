import { defineCommand } from 'citty'
import { createContext } from '../context'

async function loadRoutes(ctx: ReturnType<typeof createContext>, file?: string) {
  const candidates = file ? [file] : ['server/routes.ts', 'app/api/routes.ts', 'start/routes.ts']
  const path = candidates
    .map((c) => ctx.path(c))
    .find((p) => ctx.exists(p.slice(ctx.root.length + 1)))
  if (!path) throw new Error(`No routes file found (${candidates.join(', ')}). Pass --file.`)
  const { createJiti } = await import('jiti')
  const jiti = createJiti(ctx.path('package.json'), { alias: readAliases(ctx) })
  const mod = (await jiti.import(path)) as Record<string, unknown>
  const api = (await jiti.import('kitr/api')) as {
    toOpenApi: (
      router: unknown,
      info: { title: string; version: string; description?: string },
    ) => Promise<unknown>
  }
  const router = (mod.routes ?? mod.default) as
    | { routes: unknown[]; toJSON(): unknown[] }
    | undefined
  if (!router || typeof router.toJSON !== 'function')
    throw new Error(`${path} must export \`routes\` from defineRoutes()`)
  return { router, path, api, jiti }
}

/** What `config/api.ts` sets, loaded the way the app loads it. Empty when there is no file. */
export interface ApiSyncConfig {
  prefix?: string
  openapi?: { path?: string; title?: string; version?: string; description?: string }
  client?: { path?: string }
}

/**
 * The output paths and document info `kitr api:sync` uses: `openapi.*` from config/api.ts, the
 * route table next to `client.path` (default `app/api/client.ts`, or `server/` for a backend).
 */
export function syncPlan(
  config: ApiSyncConfig,
  project: { name?: string; version?: string; hasAppApi: boolean },
  out?: string,
) {
  const clientDir = config.client?.path
    ? config.client.path.replace(/\/[^/]*\.[cm]?[jt]sx?$/, '')
    : project.hasAppApi
      ? 'app/api'
      : 'server'
  return {
    out: out ?? config.openapi?.path ?? 'openapi.json',
    tablePath: `${clientDir.replace(/\/$/, '')}/routes.gen.ts`,
    info: {
      title: config.openapi?.title ?? `${project.name ?? 'app'} API`,
      version: config.openapi?.version ?? project.version ?? '0.0.0',
      ...(config.openapi?.description ? { description: config.openapi.description } : {}),
    },
  }
}

/** Routes outside `prefix`: the catch-all that forwards `prefix/*` to the server never reaches them. */
export function outsidePrefix(routes: Array<{ path: string }>, prefix?: string): string[] {
  if (!prefix || prefix === '/') return []
  const base = prefix.replace(/\/$/, '')
  return routes.map((r) => r.path).filter((path) => path !== base && !path.startsWith(`${base}/`))
}

function readAliases(ctx: ReturnType<typeof createContext>): Record<string, string> {
  const out: Record<string, string> = {}
  try {
    const ts = JSON.parse(ctx.read('tsconfig.json'))
    for (const [k, v] of Object.entries<string[]>(ts.compilerOptions?.paths ?? {}))
      out[k.replace('/*', '')] = ctx.path(v[0]!.replace('/*', ''))
  } catch {}
  return out
}

export const apiSync = defineCommand({
  meta: {
    name: 'api:sync',
    description: 'Write the OpenAPI document and the client route table from your routes file.',
  },
  args: {
    file: {
      type: 'string',
      description: 'Routes file (default: server/routes.ts)',
    },
    out: {
      type: 'string',
      description: 'OpenAPI output path (default: openapi.path in config/api.ts, or openapi.json)',
    },
  },
  async run({ args }) {
    const ctx = createContext()
    const { router, api, jiti } = await loadRoutes(ctx, args.file)
    const config: ApiSyncConfig = ctx.exists('config/api.ts')
      ? ((await jiti.import(ctx.path('config/api.ts'), { default: true })) ?? {})
      : {}
    const { out, tablePath, info } = syncPlan(
      config,
      { name: ctx.pkg.name, version: ctx.pkg.version, hasAppApi: ctx.exists('app/api') },
      args.out,
    )
    const doc = await api.toOpenApi(router, info)
    ctx.write(out, `${JSON.stringify(doc, null, 2)}\n`, { overwrite: true })
    const table = router.toJSON() as Array<{ name?: string; method: string; path: string }>
    for (const path of outsidePrefix(table, config.prefix))
      ctx.log.warn(
        `${path} is outside prefix ${config.prefix} (config/api.ts), so requests to it never reach the server`,
      )
    ctx.write(
      tablePath,
      `// Generated by \`kitr api:sync\`. Do not edit.\nexport const routeTable = ${JSON.stringify(
        table.map((r) => ({ name: r.name, method: r.method, path: r.path })),
        null,
        2,
      )} as const\n`,
      { overwrite: true },
    )
    ctx.log.success(`${table.length} routes → ${out}, ${tablePath}`)
  },
})

export const routesList = defineCommand({
  meta: { name: 'routes:list', description: 'Print the API route table.' },
  args: { file: { type: 'string' } },
  async run({ args }) {
    const ctx = createContext()
    const { router } = await loadRoutes(ctx, args.file)
    for (const r of router.toJSON() as Array<{ method: string; path: string; name: string }>)
      ctx.log.plain(`  ${r.method.padEnd(7)} ${r.path.padEnd(40)} ${r.name}`)
  },
})
