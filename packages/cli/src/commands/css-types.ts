import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { defineCommand } from 'citty'
import { createContext } from '../context'

/** Collect class names from a CSS module source. Nested selectors and `composes` are handled by the regex good enough for generated typings. */
export function classNamesOf(css: string): string[] {
  const stripped = css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/:global\([^)]*\)/g, '')
  const names = new Set<string>()
  for (const m of stripped.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) names.add(m[1]!)
  return [...names].sort()
}

export function renderDts(names: string[]): string {
  const toKey = (n: string) => (/^[A-Za-z_$][\w$]*$/.test(n) ? n : JSON.stringify(n))
  return `// Generated by \`kitr css:types\`. Do not edit.\ndeclare const classes: {\n${names.map((n) => `  readonly ${toKey(n)}: string`).join('\n')}\n}\nexport default classes\n`
}

function* walk(dir: string): Generator<string> {
  for (const entry of readdirSync(dir)) {
    const full = `${dir}/${entry}`
    if (entry === 'node_modules' || entry.startsWith('.')) continue
    if (statSync(full).isDirectory()) yield* walk(full)
    else if (full.endsWith('.module.css')) yield full
  }
}

export const cssTypes = defineCommand({
  meta: {
    name: 'css:types',
    description:
      'Write a .d.ts next to every *.module.css so class names are typed (for projects that prefer CSS Modules over Tailwind).',
  },
  args: {
    dir: { type: 'string', description: 'Directory to scan', default: 'app' },
    check: {
      type: 'boolean',
      description: 'Fail if any .d.ts is stale instead of writing',
      default: false,
    },
  },
  run({ args }) {
    const ctx = createContext()
    const root = ctx.path(args.dir)
    let count = 0
    let stale = 0
    for (const file of walk(root)) {
      const dts = renderDts(classNamesOf(readFileSync(file, 'utf8')))
      const target = `${file}.d.ts`
      let current = ''
      try {
        current = readFileSync(target, 'utf8')
      } catch {}
      if (current === dts) continue
      if (args.check) {
        stale++
        ctx.log.warn(`stale: ${target.slice(ctx.root.length + 1)}`)
      } else {
        writeFileSync(target, dts)
        count++
        ctx.log.step(`write ${target.slice(ctx.root.length + 1)}`)
      }
    }
    if (args.check) {
      if (stale) process.exitCode = 1
      else ctx.log.success('CSS module typings are up to date')
    } else ctx.log.success(`${count} file(s) written`)
  },
})
