import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { defineTypes, type GenerateContext, type GeneratedFile } from '@kitr/core'
import { displayName } from '@kitr/core/package'
import { type BuiltContent, buildContent, normalizePath } from './collections'
import type { ContentConfig } from './model'

/**
 * The `content` generator for `kitr generate` (and `kitr types`, `kitr dev`, `kitr build`). It
 * reads `config/content.ts`, renders every collection's markdown and writes `.kitr/content/`:
 * one JSON file per page, each collection's nav, the search index, `llms.json` when `llms` is on,
 * and `index.ts`, the typed module the app imports as `#kitr/content`.
 */

/** The folder under `.kitr/` this generator writes. */
export const OUT_DIR = 'content'

/**
 * Run `config/content.ts` with jiti from the project root, the way the CLI runs `kitrrc.ts`, so
 * the file can import `defineConfig` from `@kitr/content` and compute values. `undefined` when
 * the project has no such file.
 */
export async function loadContentConfig(
  root: string,
  configDir = 'config',
): Promise<ContentConfig | undefined> {
  const file = join(root, configDir, 'content.ts')
  if (!existsSync(file)) return undefined
  const { createJiti } = await import('jiti')
  const jiti = createJiti(join(root, 'package.json'), { moduleCache: false, fsCache: false })
  const config = await jiti.import<ContentConfig>(file, { default: true })
  if (!config || typeof config !== 'object' || typeof config.collections !== 'object')
    throw new Error(
      `${configDir}/content.ts must export defineConfig({ collections: { ... } }) as its default`,
    )
  return config
}

const isIdentifier = (s: string) => /^[A-Za-z_$][\w$]*$/.test(s)
const key = (s: string) => (isIdentifier(s) ? s : JSON.stringify(s))
const quote = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

/** `.kitr/content/index.ts`: the nav inline, typed slugs, and lazy loaders for pages and search. */
export function renderIndex(content: Pick<BuiltContent, 'nav'>): string {
  const names = Object.keys(content.nav)
  const slugs = names.map((name) => {
    const all = content.nav[name]!.flatMap((g) => g.items.map((i) => i.slug))
    return `  ${key(name)}: ${all.length ? all.map(quote).join(' | ') : 'never'}`
  })
  const nav = names.map(
    (name) =>
      `  ${key(name)}: ${JSON.stringify(content.nav[name], null, 2).replace(/\n/g, '\n  ')},`,
  )
  const block = (lines: string[]) => (lines.length ? `{\n${lines.join('\n')}\n}` : '{}')
  return `// Generated by \`kitr generate\` from config/content.ts and its markdown. Do not edit.
import type { NavGroup, Page, SearchEntry } from '@kitr/content'

/** Every page's slug, by collection. */
export interface Slugs ${block(slugs)}

/** A collection named in config/content.ts. */
export type Collection = keyof Slugs

/** The slugs of one collection: \`Slug<'docs'>\`. */
export type Slug<C extends Collection> = Slugs[C]

/** Each collection's pages, grouped and ordered as its nav.json lists them. */
export const nav: { [C in Collection]: NavGroup<Slug<C>>[] } = ${block(nav)}

const pages = import.meta.glob<Page>('./*/*.json', { import: 'default' })
const searchIndex = import.meta.glob<SearchEntry[]>('./search.json', { import: 'default' })

/** One page's rendered content, loaded on demand; \`null\` when the collection has no such page. */
export async function loadPage(collection: Collection, slug: string): Promise<Page | null> {
  const load = pages[\`./\${collection}/\${slug}.json\`]
  return load ? load() : null
}

/** The search index for \`search()\` from @kitr/content, loaded on first use. */
export function loadSearch(): Promise<SearchEntry[]> {
  return searchIndex['./search.json']?.() ?? Promise.resolve([])
}
`
}

/** The generated files for built content, relative to `.kitr/`. */
export function contentFiles(content: BuiltContent): GeneratedFile[] {
  const files: GeneratedFile[] = []
  const json = (file: string, value: unknown, pretty = false) =>
    files.push({
      file: `${OUT_DIR}/${file}`,
      content: `${JSON.stringify(value, null, pretty ? 2 : undefined)}\n`,
    })
  for (const p of content.pages) json(`${p.collection}/${p.slug}.json`, p.page)
  for (const [name, groups] of Object.entries(content.nav)) json(`${name}.nav.json`, groups, true)
  json('search.json', content.search)
  if (content.llms) json('llms.json', content.llms, true)
  files.push({ file: `${OUT_DIR}/index.ts`, content: renderIndex(content) })
  return files
}

/** The default `llms.txt` title: the package.json `name` as words (`acme-docs` is `Acme Docs`). */
function packageName(ctx: GenerateContext): string | undefined {
  try {
    const name = JSON.parse(ctx.read('package.json')).name
    return typeof name === 'string' && name ? displayName(name) : undefined
  } catch {
    return undefined
  }
}

/**
 * The folders the generator reads, from the `source:` values in `config/content.ts`, read as text
 * so `watch` stays cheap. `content/` is always watched.
 */
function watchedSources(configDir: string): string[] {
  const sources = new Set(['content'])
  try {
    const text = readFileSync(join(process.cwd(), configDir, 'content.ts'), 'utf8')
    for (const m of text.matchAll(/\bsource\s*:\s*['"`]([^'"`]+)['"`]/g))
      sources.add(normalizePath(m[1]!))
  } catch {}
  return [...sources].flatMap((s) => [`${s}/**/*.md`, `${s}/**/*.json`])
}

export default defineTypes({
  name: 'content',
  watch: (rc) => {
    const configDir = rc.directories.config ?? 'config'
    return [`${configDir}/content.ts`, ...watchedSources(configDir)]
  },
  async generate(ctx) {
    const config = (await loadContentConfig(ctx.root, ctx.rc.directories.config ?? 'config')) ?? {
      collections: {},
    }
    const name = packageName(ctx)
    const content = await buildContent(ctx, config, name ? { name } : {})
    return contentFiles(content)
  },
})
