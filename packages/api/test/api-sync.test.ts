import { describe, expect, it } from 'vitest'
import { outsidePrefix, syncPlan } from '../src/commands'

const project = { name: 'acme', version: '1.2.3', hasAppApi: true }

// `kitr api:sync` reads every option in config/api.ts: `prefix`, `openapi.path`,
// `openapi.description` and `client.path`.
describe('kitr api:sync config', () => {
  it('defaults from package.json and the project layout', () => {
    expect(syncPlan({}, project)).toEqual({
      out: 'openapi.json',
      tablePath: 'app/api/routes.gen.ts',
      info: { title: 'acme API', version: '1.2.3' },
    })
    expect(syncPlan({}, { ...project, hasAppApi: false }).tablePath).toBe('server/routes.gen.ts')
  })

  it('reads openapi.path, title, version and description, and client.path', () => {
    const plan = syncPlan(
      {
        client: { path: 'src/http/client.ts' },
        openapi: { path: 'docs/openapi.json', title: 'Acme', version: '2', description: 'The API' },
      },
      project,
    )
    expect(plan).toEqual({
      out: 'docs/openapi.json',
      tablePath: 'src/http/routes.gen.ts',
      info: { title: 'Acme', version: '2', description: 'The API' },
    })
    // client.path declared before openapi.path does not take the OpenAPI output path.
    expect(syncPlan({ client: { path: 'app/api/client.ts' } }, project).out).toBe('openapi.json')
    expect(syncPlan({ openapi: { path: 'a.json' } }, project, 'b.json').out).toBe('b.json')
  })

  it('finds routes outside the prefix', () => {
    const routes = [{ path: '/api/health' }, { path: '/api' }, { path: '/apix' }, { path: '/me' }]
    expect(outsidePrefix(routes, '/api')).toEqual(['/apix', '/me'])
    expect(outsidePrefix(routes, '/api/')).toEqual(['/apix', '/me'])
    expect(outsidePrefix(routes, undefined)).toEqual([])
  })
})

import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { afterAll, beforeAll, vi } from 'vitest'
import { apiSync, routesList } from '../src/commands'

// The commands run in a throwaway project whose tsconfig paths point `@kitr/api` at this
// package's source, the way a kitr app's `#server/*` alias points into the app.
describe('kitr api:sync and routes:list', () => {
  const dir = mkdtempSync(join(tmpdir(), 'kitr-api-sync-'))
  const cwd = process.cwd()
  const logs: string[] = []

  beforeAll(() => {
    writeFileSync(join(dir, 'package.json'), JSON.stringify({ name: 'acme', version: '3.0.0' }))
    writeFileSync(
      join(dir, 'tsconfig.json'),
      JSON.stringify({
        compilerOptions: { paths: { '@kitr/api': [resolve(__dirname, '../src/index.ts')] } },
      }),
    )
    process.chdir(dir)
    vi.spyOn(console, 'log').mockImplementation((line: string) => {
      logs.push(String(line))
    })
  })

  afterAll(() => {
    process.chdir(cwd)
    vi.restoreAllMocks()
    rmSync(dir, { recursive: true, force: true })
  })

  it('fails clearly without a routes file', async () => {
    await expect(apiSync.run({ args: {} })).rejects.toThrow(/No routes file found/)
  })

  it('writes openapi.json and the client route table, then lists the routes', async () => {
    const { mkdirSync } = await import('node:fs')
    mkdirSync(join(dir, 'server'), { recursive: true })
    mkdirSync(join(dir, 'config'), { recursive: true })
    writeFileSync(
      join(dir, 'server/routes.ts'),
      `import { defineRoutes } from '@kitr/api'
class Health { async show() { return { ok: true } } }
export const routes = defineRoutes((root) =>
  root.group('/api', (r) => {
    r.get('/health', [Health, 'show'], { name: 'health' })
  }),
)
`,
    )
    writeFileSync(
      join(dir, 'config/api.ts'),
      `export default { prefix: '/api', openapi: { path: 'docs/openapi.json', title: 'Acme', version: '9' } }\n`,
    )
    await apiSync.run({ args: {} })
    const doc = JSON.parse(readFileSync(join(dir, 'docs/openapi.json'), 'utf8'))
    expect(doc.info).toEqual({ title: 'Acme', version: '9' })
    expect(Object.keys(doc.paths)).toEqual(['/api/health'])
    const table = readFileSync(join(dir, 'server/routes.gen.ts'), 'utf8')
    expect(table).toContain('// Generated by `kitr api:sync`. Do not edit.')
    expect(table).toContain('"name": "health"')
    expect(logs.at(-1)).toContain('1 routes → docs/openapi.json, server/routes.gen.ts')

    logs.length = 0
    await routesList.run({ args: {} })
    expect(logs).toHaveLength(1)
    expect(logs[0]).toMatch(/GET\s+\/api\/health\s+health/)
  })
})
